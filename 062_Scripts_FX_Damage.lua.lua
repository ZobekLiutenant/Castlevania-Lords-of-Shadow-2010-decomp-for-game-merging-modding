function FXDamage.Impact(tipo, entity, pos)
  print("IMPACCCCCCCCCT")
  local maxDist = 100
  local dir = pos - entity.Pos
  local dist = dir:mod()
  if maxDist < dist then
    dir = dir * maxDist / dist
  end
  pos = entity.Pos + dir
  if FX.BeginEffect("EFFECT_PARTICLES\183" .. tipo .. "_CIMPACT", "") then
    FX.SetEffect("EFFECT_PARTICLES\183" .. tipo .. "_CIMPACT", "", "MatrixTranslation " .. pos:str3())
