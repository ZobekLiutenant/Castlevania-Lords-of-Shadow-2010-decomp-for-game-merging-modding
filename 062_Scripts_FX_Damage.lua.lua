end

function FXDamage.FXAutoExplode(entityName)
  local entity = Game.GetEntity(entityName)
  local tipo = FXDamage.BloodList[entity.ActCtrl]
  if tipo ~= nil and tipo[4] ~= nil then
    local pos = entity.Pos
    if tipo[5] ~= nil then
      pos = FX.GetNodePosition(entityName, tipo[5])
    end
    local type = "EFFECT_PARTICLES\183AUTOEXPLODE_" .. FXDamage.BloodList[entity.ActCtrl][4]
    if FX.BeginEffect(type, "") and pos then
      local batches = FX.GetEffect(type, "", "EmittersCount -1")
      for i = 0, batches - 1 do
        local emitters = FX.GetEffect(type, "", "EmittersCount " .. i)
        for j = 0, emitters - 1 do
          FX.SetEffect(type, "", "EmitterMatrixTranslation " .. i .. "," .. j .. "," .. pos:str3())
        end
      end
      SoundUtils.FXPlaySound("Belmont", "Explosion_" .. FXDamage.BloodList[entity.ActCtrl][4], pos)
    end
  end
  if entity.uData.DeadByMagic and (entity.uData.DeadByMagic == "dark" or entity.uData.DeadByMagic == "light") then
    addSF(4, "Weapons.RemoveChar", entityName)
    return
  end
  Weapons.RemoveChar(entityName)
end

