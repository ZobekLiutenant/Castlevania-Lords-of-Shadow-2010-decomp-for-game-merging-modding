function FXDamage.FireOn(entityName, time)
  local tipo = tostring(Game.GetEntity(entityName).oActCtrl.oActClass.Name)
  local density = FXDamage.DensityTable[tipo]
  density = density or FXDamage.DensityTable.Default
  local t = "bonzo_calima_" .. entityName
  if FX.IsEffect("EFFECT_RAGDOLL\183FIRECALIMA", t) then
    Game.DeleteScheduledFuncs("Fire_off" .. entityName)
    FXDamage.FireOffFinal(entityName)
  end
  if not FX.IsEffect("EFFECT_RAGDOLL\183FIRECALIMA", t) and FX.BeginEffect("EFFECT_RAGDOLL\183FIRECALIMA", t, entityName) ~= nil then
    FX.SetEffect("EFFECT_RAGDOLL\183FIRECALIMA", t, "LinkToEmitter")
    FXDamage.FireSetupNodes("EFFECT_RAGDOLL\183FIRECALIMA", t, tipo)
  end
  t = "bonzo_free_" .. entityName
  if not FX.IsEffect("EFFECT_RAGDOLL\183FIREFREE", t) and FX.BeginEffect("EFFECT_RAGDOLL\183FIREFREE", t, entityName .. "," .. density) ~= nil then
    FX.SetEffect("EFFECT_RAGDOLL\183FIREFREE", t, "LinkToEmitter")
    FXDamage.FireSetupNodes("EFFECT_RAGDOLL\183FIREFREE", t, tipo)
  end
  t = "bonzo_link_" .. entityName
  if not FX.IsEffect("EFFECT_RAGDOLL\183FIRELINK", t) and FX.BeginEffect("EFFECT_RAGDOLL\183FIRELINK", t, entityName .. "," .. density) ~= nil then
    FXDamage.FireSetupNodes("EFFECT_RAGDOLL\183FIRELINK", t, tipo)
  end
  if time then
    Game.AddScheduledFunc(Game.GetTime() + time, "", "FXDamage.FireOff", entityName)
  end
end

function FXDamage.FireSetupNodes(effect, t, tipo)
  local lista = FXDamage.NodeList[tipo]
  if lista then
    FX.SetEffect(effect, t, "DeActiveAll")
    local i
    for i = 1, #lista do
      print(lista[i])
      FX.SetEffect(effect, t, "ActiveEmitter " .. lista[i])
    end
  end
end

