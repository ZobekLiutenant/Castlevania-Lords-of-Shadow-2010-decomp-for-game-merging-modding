function FXDamage.DeathPlay(EntityName, delay)
  local time = defparam(delay, 0)
  local ent = Game.GetEntity(EntityName)
  if ent.Hit_RemoveNow == 1 then
    NPC.DeleteEntity(EntityName)
  else
    if ent.uData.DeadByMagic then
      if ent.uData.DeadByMagic == "dark" then
        print("DeadMagicDark")
        time = 0.2
        Game.AddScheduledFunc(Game.GetTime() + time, "", "FXDamage.DeathExecDark", EntityName)
        return
      elseif ent.uData.DeadByMagic == "light" then
        print("DeadMagicLight")
        time = 0.2
        Game.AddScheduledFunc(Game.GetTime() + time, "", "FXDamage.DeathExecLight", EntityName)
        return
      end
    end
    if Game.GetEntity(EntityName).uData.AutoExplode then
    else
      Game.AddScheduledFunc(Game.GetTime() + time, "", "FXDamage.DeathExec", EntityName)
    end
  end
end

function FXDamage.DeathExec(EntityName)
  NPC.DisolveBurnEntity(EntityName, 2)
  Game.AddScheduledFunc(Game.GetTime() + 5, EntityName, "NPC.DeleteEntity", EntityName)
