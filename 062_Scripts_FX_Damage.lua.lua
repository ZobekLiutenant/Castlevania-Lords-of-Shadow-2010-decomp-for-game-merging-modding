function FXDamage.StartCrazyFX(EntityName, iCrazyMode)
  local entity = Game.GetEntity(EntityName)
  local tipo = entity.ActCtrl
  if iCrazyMode == 1 and (FXDamage.CrazyList[tipo] == nil or FXDamage.CrazyList[tipo][1] == nil) then
    Fairy.FXCrazyOn(EntityName)
  end
  if FXDamage.CrazyList[tipo] ~= nil then
    local crazy = FXDamage.CrazyList[tipo][iCrazyMode]
    if crazy ~= nil then
      local efecto = "EFFECT_PARTICLES\183" .. crazy[1]
      local pos = crazy[3]:rot(crazy[4]:todeg())
      local ang = crazy[4]
      if FX.IsEffect(efecto, "Crazy_" .. EntityName .. "_" .. iCrazyMode) then
        FX.EndEffect(efecto, "Crazy_" .. EntityName .. "_" .. iCrazyMode)
      end
      if FX.BeginEffect(efecto, "Crazy_" .. EntityName .. "_" .. iCrazyMode) then
        FX.SetEffect(efecto, "", "LinkToNode " .. EntityName .. "#" .. crazy[2])
        FX.SetEffect(efecto, "", "MatrixTranslation " .. pos:str3())
        FX.SetEffect(efecto, "", "MatrixEuler " .. ang:str3())
      end
    end
  end
end

function FXDamage.StopCrazyFX(EntityName)
  local tipo = Game.GetEntity(EntityName).ActCtrl
  Fairy.FXCrazyOff(EntityName)
  if FXDamage.CrazyList[tipo] ~= nil then
    for iCrazyMode = 0, 4 do
      local crazy = FXDamage.CrazyList[tipo][iCrazyMode]
      if crazy ~= nil then
        local efecto = "EFFECT_PARTICLES\183" .. crazy[1]
        local nombre_efecto = "Crazy_" .. EntityName .. "_" .. iCrazyMode
        if FX.IsEffect(efecto, nombre_efecto) then
          FX.SetEffect(efecto, nombre_efecto, "LifeTimeRemain 0.5")
          local batches = FX.GetEffect(efecto, nombre_efecto, "EmittersCount -1")
          for i = 0, batches - 1 do
            local emitters = FX.GetEffect(efecto, nombre_efecto, "EmittersCount " .. i)
            for j = 0, emitters - 1 do
              FX.SetEffect(efecto, nombre_efecto, "AlphaFadeOutEmitterSpeed " .. i .. "," .. j .. ",4")
            end
          end
        end
      end
    end
  end
end

