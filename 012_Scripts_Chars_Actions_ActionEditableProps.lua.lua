function ActionEditableProps.GetDefault(name, action)
  for i, entry in pairs(ActionEditableProps.Props) do
    if entry[1] == name then
      if entry[3] ~= "COMBATLINK" then
        return entry[7]
      else
        local group
        if GabrielCombos.DefaultLinks[action.Group] then
          group = GabrielCombos.DefaultLinks[action.Group]
        else
          group = GabrielCombos.DefaultLinks.Default
        end
        return group[entry[7]]
      end
    end
  end
  return nil
end
